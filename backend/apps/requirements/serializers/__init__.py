"""Wire shapes for the M2 requirement, enquiry and proposal surface.

Two rules run through this file and neither is negotiable:

* **A requirement is free.** Nothing in the Customer requirement serializers carries a price,
  quotes one, or hints that one is coming. `is_free` on the submit response is read from the
  server that enforces the rule rather than hardcoded in a screen that outlives it.
* **A teaser is not a quote.** `QuoteTeaserSerializer` is an explicit field list, never a
  `ModelSerializer`. Before an active unlock the response must not carry vendor identity, contact,
  scope or an exact total — not in a field the UI happens not to render, because a client cannot
  un-receive a payload and cached identity survives a refund.

The shapes are split across submodules along the waves they were built in. Every name below is
re-exported here, so `apps.requirements.serializers.Anything` still resolves:

* `base` — the three request vocabularies more than one slice reads. Imports no sibling.
* `capture` — Customer: requirement capture, attachments, `My requests`, and the teaser read.
* `enquiries` — clarification and site visits (both roles), then the Partner enquiry and composer.
* `engagements` — Wave C2: the unlock and visit-plan front doors, selection, and the engagement.
* `partner` — the A5 visit-slot grid, workspace grants, and the masked demand preview.
* `rate_cards` — Wave C2R / revision 4: the rate-card A3 front door and the crew offer.
* `shifts` — Wave C4: the shift-day, its attendance, its settlement, safety and cash reports.
* `projects` — Wave C5: the A5 project surface, handover, delay claims and transfers.
* `operations` — Wave C6: cancellation, cases, assisted capture and the Operations workspace.
"""

