"""Private object storage boundary, shared by every app that needs a signed-upload document flow.

Provider credentials remain server-side. Object keys are generated by Django and every accepted
upload is streamed back through this boundary for size, media-type and SHA-256 verification.
`apps.partners` (KYC documents) and `apps.fulfilment` (work evidence) each call
`get_document_storage(bucket=...)` with their own bucket — there is one implementation per
provider (Cloudflare R2 or Supabase), not one per app. On R2 each "bucket" is a folder inside
the one private bucket.
"""

import hashlib
from dataclasses import dataclass
from datetime import datetime, timedelta
from http import HTTPStatus
from typing import Any, NoReturn, Protocol, cast
from urllib.parse import parse_qs, quote, urlparse

import requests
from django.conf import settings
from django.utils import timezone

SIGNED_UPLOAD_LIFETIME = timedelta(hours=2)
DOWNLOAD_CHUNK_SIZE = 64 * 1024


class DocumentStorageError(RuntimeError):
    """Raised when private object storage cannot complete a safe operation."""


@dataclass(frozen=True, slots=True)
class SignedUpload:
    upload_url: str
    upload_token: str
    resumable_url: str
    expires_at: datetime
    method: str = "PUT"


@dataclass(frozen=True, slots=True)
class VerifiedObject:
    size_bytes: int
    content_type: str
    sha256: str


@dataclass(frozen=True, slots=True)
class SignedReview:
    review_url: str
    expires_at: datetime


class DocumentStorage(Protocol):
    def create_signed_upload(self, *, object_key: str) -> SignedUpload: ...

    def verify_object(self, *, object_key: str, maximum_size_bytes: int) -> VerifiedObject: ...

    def create_signed_review(self, *, object_key: str, expires_in_seconds: int) -> SignedReview: ...

    def delete_object(self, *, object_key: str) -> None: ...


class UnconfiguredDocumentStorage:
    @staticmethod
    def _raise() -> NoReturn:
        raise DocumentStorageError("Private document storage is not configured.")

    def create_signed_upload(self, *, object_key: str) -> SignedUpload:
        del object_key
        self._raise()

    def verify_object(self, *, object_key: str, maximum_size_bytes: int) -> VerifiedObject:
        del object_key, maximum_size_bytes
        self._raise()

    def create_signed_review(self, *, object_key: str, expires_in_seconds: int) -> SignedReview:
        del object_key, expires_in_seconds
        self._raise()

    def delete_object(self, *, object_key: str) -> None:
        del object_key
        self._raise()


class SupabaseDocumentStorage:
    def __init__(
        self,
        *,
        storage_url: str,
        service_role_key: str,
        bucket: str,
        connect_timeout_seconds: float,
        read_timeout_seconds: float,
    ) -> None:
        self.storage_url = storage_url.rstrip("/")
        self.bucket = bucket
        self.headers = {
            "Authorization": f"Bearer {service_role_key}",
            "apikey": service_role_key,
        }
        self.timeout = (connect_timeout_seconds, read_timeout_seconds)

    def _object_path(self, object_key: str) -> str:
        return quote(f"{self.bucket}/{object_key}", safe="/")

    @staticmethod
    def _json(response: requests.Response) -> dict[str, Any]:
        try:
            payload = response.json()
        except requests.exceptions.JSONDecodeError as exc:
            raise DocumentStorageError("Storage returned an invalid response.") from exc
        if not isinstance(payload, dict):
            raise DocumentStorageError("Storage returned an invalid response.")
        return cast(dict[str, Any], payload)

    @staticmethod
    def _raise_for_status(response: requests.Response) -> None:
        try:
            response.raise_for_status()
        except requests.RequestException as exc:
            raise DocumentStorageError(
                "Private document storage is temporarily unavailable."
            ) from exc

    def create_signed_upload(self, *, object_key: str) -> SignedUpload:
        try:
            response = requests.post(
                f"{self.storage_url}/object/upload/sign/{self._object_path(object_key)}",
                headers=self.headers,
                json={},
                timeout=self.timeout,
            )
        except requests.RequestException as exc:
            raise DocumentStorageError(
                "Private document storage is temporarily unavailable."
            ) from exc
        self._raise_for_status(response)
        relative_url = self._json(response).get("url")
        if not isinstance(relative_url, str) or not relative_url.startswith("/object/upload/sign/"):
            raise DocumentStorageError("Storage returned an invalid signed upload URL.")
        upload_url = f"{self.storage_url}{relative_url}"
        upload_tokens = parse_qs(urlparse(upload_url).query).get("token", [])
        if len(upload_tokens) != 1 or not upload_tokens[0]:
            raise DocumentStorageError("Storage returned an invalid signed upload token.")
        return SignedUpload(
            upload_url=upload_url,
            upload_token=upload_tokens[0],
            resumable_url=f"{self.storage_url}/upload/resumable",
            expires_at=timezone.now() + SIGNED_UPLOAD_LIFETIME,
        )

    def verify_object(self, *, object_key: str, maximum_size_bytes: int) -> VerifiedObject:
        try:
            response = requests.get(
                f"{self.storage_url}/object/{self._object_path(object_key)}",
                headers=self.headers,
                stream=True,
                timeout=self.timeout,
            )
        except requests.RequestException as exc:
            raise DocumentStorageError(
                "Private document storage is temporarily unavailable."
            ) from exc
        try:
            self._raise_for_status(response)
            declared_size = response.headers.get("Content-Length")
            if declared_size is not None and int(declared_size) > maximum_size_bytes:
                raise DocumentStorageError("The uploaded document exceeds the allowed size.")
            digest = hashlib.sha256()
            size_bytes = 0
            for chunk in response.iter_content(chunk_size=DOWNLOAD_CHUNK_SIZE):
                if not chunk:
                    continue
                size_bytes += len(chunk)
                if size_bytes > maximum_size_bytes:
                    raise DocumentStorageError("The uploaded document exceeds the allowed size.")
                digest.update(chunk)
            content_type = (
                response.headers.get("Content-Type", "").partition(";")[0].strip().lower()
            )
            return VerifiedObject(
                size_bytes=size_bytes,
                content_type=content_type,
                sha256=digest.hexdigest(),
            )
        except ValueError as exc:
            raise DocumentStorageError("Storage returned invalid object metadata.") from exc
        finally:
            response.close()

    def create_signed_review(self, *, object_key: str, expires_in_seconds: int) -> SignedReview:
        try:
            response = requests.post(
                f"{self.storage_url}/object/sign/{self._object_path(object_key)}",
                headers=self.headers,
                json={"expiresIn": expires_in_seconds},
                timeout=self.timeout,
            )
        except requests.RequestException as exc:
            raise DocumentStorageError(
                "Private document storage is temporarily unavailable."
            ) from exc
        self._raise_for_status(response)
        relative_url = self._json(response).get("signedURL")
        if not isinstance(relative_url, str) or not relative_url.startswith("/object/sign/"):
            raise DocumentStorageError("Storage returned an invalid signed review URL.")
        return SignedReview(
            review_url=f"{self.storage_url}{relative_url}",
            expires_at=timezone.now() + timedelta(seconds=expires_in_seconds),
        )

    def delete_object(self, *, object_key: str) -> None:
        try:
            response = requests.delete(
                f"{self.storage_url}/object/{quote(self.bucket, safe='')}",
                headers=self.headers,
                json={"prefixes": [object_key]},
                timeout=self.timeout,
            )
        except requests.RequestException as exc:
            raise DocumentStorageError(
                "Private document storage is temporarily unavailable."
            ) from exc
        if response.status_code == HTTPStatus.NOT_FOUND:
            return
        self._raise_for_status(response)


class R2DocumentStorage:
    """Cloudflare R2 (S3-compatible). One private bucket; each logical bucket is a folder in it.

    The browser uploads with a plain signed ``PUT`` (no token), the same shape the apps already
    send. Verification streams the object back, exactly like the Supabase implementation.
    """

    def __init__(self, *, client: Any, bucket: str, folder: str) -> None:
        self.client = client
        self.bucket = bucket
        self.folder = folder.strip("/")

    def _key(self, object_key: str) -> str:
        return f"{self.folder}/{object_key}" if self.folder else object_key

    @staticmethod
    def _unavailable() -> DocumentStorageError:
        return DocumentStorageError("Private document storage is temporarily unavailable.")

    def create_signed_upload(self, *, object_key: str) -> SignedUpload:
        try:
            upload_url = self.client.generate_presigned_url(
                "put_object",
                Params={"Bucket": self.bucket, "Key": self._key(object_key)},
                ExpiresIn=int(SIGNED_UPLOAD_LIFETIME.total_seconds()),
            )
        except Exception as exc:
            raise self._unavailable() from exc
        if not isinstance(upload_url, str) or not upload_url.startswith("https://"):
            raise DocumentStorageError("Storage returned an invalid signed upload URL.")
        return SignedUpload(
            upload_url=upload_url,
            upload_token="",
            resumable_url="",
            expires_at=timezone.now() + SIGNED_UPLOAD_LIFETIME,
        )

    def verify_object(self, *, object_key: str, maximum_size_bytes: int) -> VerifiedObject:
        try:
            response = self.client.get_object(Bucket=self.bucket, Key=self._key(object_key))
        except Exception as exc:
            raise self._unavailable() from exc
        body = response["Body"]
        try:
            declared_size = int(response.get("ContentLength") or 0)
            if declared_size > maximum_size_bytes:
                raise DocumentStorageError("The uploaded document exceeds the allowed size.")
            digest = hashlib.sha256()
            size_bytes = 0
            for chunk in body.iter_chunks(chunk_size=DOWNLOAD_CHUNK_SIZE):
                if not chunk:
                    continue
                size_bytes += len(chunk)
                if size_bytes > maximum_size_bytes:
                    raise DocumentStorageError("The uploaded document exceeds the allowed size.")
                digest.update(chunk)
            content_type = str(response.get("ContentType") or "").partition(";")[0].strip()
            return VerifiedObject(
                size_bytes=size_bytes,
                content_type=content_type.lower(),
                sha256=digest.hexdigest(),
            )
        except (TypeError, ValueError) as exc:
            raise DocumentStorageError("Storage returned invalid object metadata.") from exc
        finally:
            body.close()

    def create_signed_review(self, *, object_key: str, expires_in_seconds: int) -> SignedReview:
        try:
            review_url = self.client.generate_presigned_url(
                "get_object",
                Params={"Bucket": self.bucket, "Key": self._key(object_key)},
                ExpiresIn=expires_in_seconds,
            )
        except Exception as exc:
            raise self._unavailable() from exc
        if not isinstance(review_url, str) or not review_url.startswith("https://"):
            raise DocumentStorageError("Storage returned an invalid signed review URL.")
        return SignedReview(
            review_url=review_url,
            expires_at=timezone.now() + timedelta(seconds=expires_in_seconds),
        )

    def delete_object(self, *, object_key: str) -> None:
        # S3 deletes are idempotent: a missing key is not an error.
        try:
            self.client.delete_object(Bucket=self.bucket, Key=self._key(object_key))
        except Exception as exc:
            raise self._unavailable() from exc


def r2_client() -> Any:
    """A boto3 S3 client pointed at the account's R2 endpoint."""
    import boto3  # noqa: PLC0415 — only loaded where R2 is used
    from botocore.config import Config  # noqa: PLC0415

    return boto3.client(
        "s3",
        endpoint_url=settings.R2_ENDPOINT_URL,
        aws_access_key_id=settings.R2_ACCESS_KEY_ID,
        aws_secret_access_key=settings.R2_SECRET_ACCESS_KEY,
        region_name="auto",
        config=Config(
            signature_version="s3v4",
            connect_timeout=settings.DOCUMENT_STORAGE_CONNECT_TIMEOUT_SECONDS,
            read_timeout=settings.DOCUMENT_STORAGE_READ_TIMEOUT_SECONDS,
            retries={"max_attempts": 3, "mode": "standard"},
        ),
    )


def get_document_storage(*, bucket: str) -> DocumentStorage:
    if settings.DOCUMENT_STORAGE_PROVIDER == "r2" and settings.R2_PRIVATE_ENABLED:
        return R2DocumentStorage(
            client=r2_client(), bucket=settings.R2_PRIVATE_BUCKET, folder=bucket
        )
    if settings.DOCUMENT_STORAGE_PROVIDER == "supabase":
        return SupabaseDocumentStorage(
            storage_url=settings.SUPABASE_STORAGE_URL,
            service_role_key=settings.SUPABASE_SERVICE_ROLE_KEY,
            bucket=bucket,
            connect_timeout_seconds=settings.DOCUMENT_STORAGE_CONNECT_TIMEOUT_SECONDS,
            read_timeout_seconds=settings.DOCUMENT_STORAGE_READ_TIMEOUT_SECONDS,
        )
    return UnconfiguredDocumentStorage()


def private_file_storage() -> Any:
    """Django storage for private files (R2 private bucket, or local disk in development).

    A callable so model fields resolve it at runtime and migrations stay provider-independent.
    """
    from django.core.files.storage import storages  # noqa: PLC0415

    return storages["private"]


_PROBE_NAME = "__vsolve_probe__"


def public_stored_name(url: str, *, folder: str) -> str | None:
    """The stored file name behind a public photo link, or None if it is not one of ours.

    Works for both places photos live: the R2 public domain (``https://media.example/stay-ads/…``)
    and local disk (``/media/stay-ads/…``, possibly with the API's host in front).
    """
    from django.core.files.storage import default_storage  # noqa: PLC0415

    probe = default_storage.url(_PROBE_NAME)
    base = probe[: -len(_PROBE_NAME)]
    clean = url.split("?", 1)[0].split("#", 1)[0]
    if base.startswith(("http://", "https://")):
        remainder = clean[len(base) :] if clean.startswith(base) else None
    else:
        path = urlparse(clean).path
        remainder = path[len(base) :] if path.startswith(base) else None
    if remainder is None or not remainder.startswith(folder):
        return None
    return remainder
